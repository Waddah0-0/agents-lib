"""Rules deciding which files a workspace keeps.

Two passes: :func:`classify_path` (name-only, cheap) and :func:`classify_content`
(inspects the first few KB). Every exclusion carries a reason string.
"""

from __future__ import annotations

import fnmatch
from dataclasses import dataclass
from pathlib import PurePosixPath

from pydantic import BaseModel, Field

