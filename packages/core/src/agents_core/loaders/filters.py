LANGUAGE_BY_FILENAME: dict[str, str] = {
    "Dockerfile": "dockerfile",
    "Makefile": "makefile",
    "CMakeLists.txt": "cmake",
    "Jenkinsfile": "groovy",
}


class FilterConfig(BaseModel):
    """User-tunable filter behaviour."""

    include_vendored: bool = False
    include_generated: bool = False
    extra_ignored_dirs: frozenset[str] = Field(default_factory=frozenset)
    extra_ignored_globs: tuple[str, ...] = ()


@dataclass(frozen=True)
class FilterDecision:
    """Outcome of a filter check."""

    keep: bool
    reason: str | None = None
    is_generated: bool = False
    is_vendored: bool = False


KEEP = FilterDecision(keep=True)


def ignored_dir_reason(name: str, config: FilterConfig | None = None) -> str | None:
    """Reason to skip a whole directory by name, or ``None`` to descend into it."""
    config = config or FilterConfig()
    if name in IGNORED_DIRS or name in config.extra_ignored_dirs:
        return "ignored_dir"
    if name in VENDORED_DIRS and not config.include_vendored:
        return "vendored"
    return None


def classify_path(rel_path: str, config: FilterConfig | None = None) -> FilterDecision:
    """Name-based rules (lockfiles, binaries, minified, generated, globs, dirs)."""
    config = config or FilterConfig()
    path = PurePosixPath(rel_path)
    name = path.name
    lower = name.lower()

    for pattern in config.extra_ignored_globs:
        if fnmatch.fnmatch(rel_path, pattern) or fnmatch.fnmatch(name, pattern):
            return FilterDecision(keep=False, reason="ignored_glob")

    is_vendored = False
    for part in path.parts[:-1]:
        reason = ignored_dir_reason(part, config)
        if reason:
            return FilterDecision(keep=False, reason=reason)
        if part in VENDORED_DIRS:
            is_vendored = True

    if name in LOCKFILES:
        return FilterDecision(keep=False, reason="lockfile")
    if path.suffix.lower() in BINARY_EXTENSIONS:
        return FilterDecision(keep=False, reason="binary")
    if lower.endswith(MINIFIED_SUFFIXES):
        return FilterDecision(keep=False, reason="minified")
    if lower.endswith(GENERATED_SUFFIXES):
        if not config.include_generated:
            return FilterDecision(keep=False, reason="generated")
        return FilterDecision(keep=True, is_generated=True, is_vendored=is_vendored)
    return FilterDecision(keep=True, is_vendored=is_vendored)


def looks_binary(head: bytes) -> bool:
    return b"\x00" in head


def looks_minified(rel_path: str, head: bytes) -> bool:
    """Very long lines in a JS/CSS file indicate minified/bundled output."""
    if PurePosixPath(rel_path).suffix.lower() not in MINIFIABLE_EXTENSIONS:
        return False
    if len(head) < 2000:
        return False
    lines = head.count(b"\n") + 1
    return len(head) / lines > 300


def has_generated_marker(head: bytes) -> bool:
    first_lines = b"\n".join(head.splitlines()[:5])
    return any(marker in first_lines for marker in GENERATED_MARKERS)


def classify_content(
    rel_path: str, head: bytes, config: FilterConfig | None = None
) -> FilterDecision:
    """Content-based rules applied to the first :data:`HEAD_BYTES` of a file."""
    config = config or FilterConfig()
    if looks_binary(head):
        return FilterDecision(keep=False, reason="binary")
    if looks_minified(rel_path, head):
        return FilterDecision(keep=False, reason="minified")
    if has_generated_marker(head):
        if not config.include_generated:
            return FilterDecision(keep=False, reason="generated")
        return FilterDecision(keep=True, is_generated=True)
    return KEEP


def detect_language(rel_path: str) -> str | None:
    path = PurePosixPath(rel_path)
    if path.name in LANGUAGE_BY_FILENAME:
        return LANGUAGE_BY_FILENAME[path.name]
    return LANGUAGE_BY_EXTENSION.get(path.suffix.lower())
