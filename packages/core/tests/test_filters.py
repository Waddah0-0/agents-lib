import pytest
from agents_core.loaders.filters import (
    FilterConfig,
    classify_content,
    classify_path,
    detect_language,
    ignored_dir_reason,
)


@pytest.mark.parametrize(
    ("name", "reason"),
    [
        ("node_modules", "ignored_dir"),
        (".git", "ignored_dir"),
        ("dist", "ignored_dir"),
        ("build", "ignored_dir"),
        ("__pycache__", "ignored_dir"),
        (".venv", "ignored_dir"),
        ("vendor", "vendored"),
        ("third_party", "vendored"),
        ("src", None),
    ],
)
def test_ignored_dirs(name: str, reason: str | None) -> None:
    assert ignored_dir_reason(name) == reason


def test_vendored_can_be_included() -> None:
    cfg = FilterConfig(include_vendored=True)
    assert ignored_dir_reason("vendor", cfg) is None
    decision = classify_path("vendor/lib/x.go", cfg)
    assert decision.keep and decision.is_vendored


def test_extra_ignored_dirs() -> None:
    assert ignored_dir_reason("fixtures", FilterConfig(extra_ignored_dirs=frozenset({"fixtures"})))


@pytest.mark.parametrize(
    ("path", "reason"),
    [
        ("package-lock.json", "lockfile"),
        ("sub/yarn.lock", "lockfile"),
        ("uv.lock", "lockfile"),
        ("Cargo.lock", "lockfile"),
        ("go.sum", "lockfile"),
        ("img/logo.PNG", "binary"),
        ("bin/tool.exe", "binary"),
        ("fonts/a.woff2", "binary"),
        ("static/app.min.js", "minified"),
        ("static/app.js.map", "minified"),
        ("proto/api_pb2.py", "generated"),
        ("api/service.pb.go", "generated"),
        ("node_modules/x/index.js", "ignored_dir"),
        ("vendor/pkg/a.go", "vendored"),
    ],
)
def test_classify_path_rejects(path: str, reason: str) -> None:
    decision = classify_path(path)
    assert not decision.keep
    assert decision.reason == reason


@pytest.mark.parametrize("path", ["src/app.py", "README.md", "web/index.ts", "Dockerfile"])
def test_classify_path_keeps(path: str) -> None:
    assert classify_path(path).keep


def test_generated_can_be_included_and_flagged() -> None:
    decision = classify_path("proto/api_pb2.py", FilterConfig(include_generated=True))
    assert decision.keep and decision.is_generated


def test_extra_glob() -> None:
    decision = classify_path("docs/a.snap", FilterConfig(extra_ignored_globs=("*.snap",)))
    assert decision.reason == "ignored_glob"


def test_content_binary_null_byte() -> None:
    assert classify_content("data.txt", b"abc\x00def").reason == "binary"


def test_content_minified_long_lines() -> None:
    head = b"var a=1;" * 600  # 4800 bytes, single line
    assert classify_content("bundle.js", head).reason == "minified"
    assert classify_content("notes.md", head).keep  # heuristic only for JS/CSS


def test_content_generated_marker() -> None:
    head = b"// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n"
    assert classify_content("x.go", head).reason == "generated"
    marker_late = b"\n" * 10 + b"# DO NOT EDIT\n"
    assert classify_content("x.py", marker_late).keep


def test_content_normal_file_kept() -> None:
    assert classify_content("app.py", b"def main():\n    return 1\n").keep


@pytest.mark.parametrize(
    ("path", "lang"),
    [
        ("a.py", "python"),
        ("a.tsx", "typescript"),
        ("a.js", "javascript"),
        ("Dockerfile", "dockerfile"),
        ("x.unknown", None),
    ],
)
def test_detect_language(path: str, lang: str | None) -> None:
    assert detect_language(path) == lang
