// Generate src/styles/theme.css: Material 3 colour roles (light and dark) built from the
// agents-lib palette (ink teal, highlighter amber, warm paper), the highlighter tokens, and
// spring easings as CSS linear() curves.
//
//   npm run gen:theme
//
// The output is committed; run this again only to change the palette or the springs.
import { writeFileSync } from "node:fs";
import { registerHooks } from "node:module";
import { fileURLToPath } from "node:url";

// The colour library's ESM build imports its own files without ".js"; Node needs it.
registerHooks({
  resolve(specifier, context, next) {
    try {
      return next(specifier, context);
    } catch (err) {
      if (specifier.startsWith(".") && !specifier.endsWith(".js")) {
        return next(`${specifier}.js`, context);
      }
      throw err;
    }
  },
});

const { DynamicScheme, Hct, MaterialDynamicColors, TonalPalette, Variant, hexFromArgb } = await import(
  "@material/material-color-utilities"
);

// HCT hue and chroma of each palette
const INK = { hue: 186, chroma: 36 }; // primary: deep ink teal
const MARKER = { hue: 84, chroma: 50 }; // tertiary: highlighter amber
const PAPER = { hue: 95, chroma: 4 }; // neutrals: warm paper
const OUT = fileURLToPath(new URL("../src/styles/theme.css", import.meta.url));

const palette = ({ hue, chroma }) => TonalPalette.fromHueAndChroma(hue, chroma);
const highlighter = TonalPalette.fromHueAndChroma(88, 80);

function roles(isDark) {
  const scheme = new DynamicScheme({
    sourceColorHct: Hct.from(INK.hue, INK.chroma, 40),
    variant: Variant.TONAL_SPOT,
    contrastLevel: 0,
    isDark,
    primaryPalette: palette(INK),
    secondaryPalette: palette({ hue: INK.hue, chroma: 12 }),
    tertiaryPalette: palette(MARKER),
    neutralPalette: palette(PAPER),
    neutralVariantPalette: palette({ hue: PAPER.hue, chroma: PAPER.chroma * 2 }),
  });
  const lines = [];
  for (const color of new MaterialDynamicColors().allColors) {
    const name = color.name.replaceAll("_", "-");
    lines.push(`  --${name}: ${hexFromArgb(color.getArgb(scheme))};`);
  }
  // the highlighter: solid on paper, translucent on dark ink so the text stays readable
  const marker = hexFromArgb(highlighter.tone(isDark ? 80 : 86));
  lines.push(
    isDark ? `  --marker: color-mix(in srgb, ${marker} 34%, transparent);` : `  --marker: ${marker};`,
  );
  lines.push(`  --marker-strong: ${hexFromArgb(highlighter.tone(isDark ? 78 : 80))};`);
  return lines.join("\n");
}

// A damped spring released from 0 towards 1 (mass 1). Returns position at time t (s).
function spring(damping, stiffness) {
  const w0 = Math.sqrt(stiffness);
  if (damping >= 1) return (t) => 1 - Math.exp(-w0 * t) * (1 + w0 * t);
  const wd = w0 * Math.sqrt(1 - damping * damping);
  return (t) =>
    1 - Math.exp(-damping * w0 * t) * (Math.cos(wd * t) + ((damping * w0) / wd) * Math.sin(wd * t));
}

// Sample the spring until it settles within 0.1% and express it as linear().
function springCss(name, damping, stiffness) {
  const x = spring(damping, stiffness);
  const settle = Math.log(1000) / (Math.min(damping, 1) * Math.sqrt(stiffness));
  const steps = 40;
  const points = [];
  for (let i = 0; i <= steps; i++) {
    const v = i === steps ? 1 : x((settle * i) / steps);
    points.push(Number(v.toFixed(4)));
  }
  const ms = Math.round(settle * 1000);
  return [`  --spring-${name}: linear(${points.join(", ")});`, `  --spring-${name}-duration: ${ms}ms;`].join(
    "\n",
  );
}

const springs = [
  springCss("fast-spatial", 0.6, 800),
  springCss("default-spatial", 0.8, 380),
  springCss("slow-spatial", 0.8, 200),
  springCss("fast-effects", 1, 3800),
  springCss("default-effects", 1, 1600),
  springCss("slow-effects", 1, 800),
].join("\n");

const css = `/* Generated by scripts/gen-theme.mjs. Do not edit by hand. */

:root {
  color-scheme: light;
${roles(false)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${roles(true).replaceAll("\n  ", "\n    ").replace(/^ {2}/, "    ")}
  }
}

:root[data-theme="dark"] {
  color-scheme: dark;
${roles(true)}
}

/* Springs (damping ratio, stiffness) as linear() curves. */
:root {
${springs}
}
`;

writeFileSync(OUT, css);
console.log(`wrote ${OUT}`);
