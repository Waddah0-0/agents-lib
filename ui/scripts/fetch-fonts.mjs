// Download the fonts into public/fonts and write src/styles/fonts.css, so the UI works
// offline and never depends on a CDN.
//
//   npm run fetch:fonts
//
// Fraunces (display), Instrument Sans (interface) and JetBrains Mono (code and evidence),
// Latin subsets. All three are under the SIL Open Font License.
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));
const OUT_DIR = root("public/fonts");
const CSS_OUT = root("src/styles/fonts.css");
// Google Fonts serves variable woff2 only to browsers it recognises
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36";

const FAMILIES = [
  {
    name: "fraunces",
    query: "family=Fraunces:opsz,wght,SOFT,WONK@9..144,100..900,0..100,0..1",
    ofl: "fraunces",
  },
  {
    name: "instrument-sans",
    query: "family=Instrument+Sans:wdth,wght@75..100,400..700",
    ofl: "instrumentsans",
  },
  { name: "jetbrains-mono", query: "family=JetBrains+Mono:wght@300..700", ofl: "jetbrainsmono" },
];
const SUBSETS = ["latin", "latin-ext"];

async function text(url) {
  const res = await fetch(url, { headers: { "user-agent": UA } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.text();
}

rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });
const blocks = [];
for (const family of FAMILIES) {
  const css = await text(`https://fonts.googleapis.com/css2?${family.query}&display=swap`);
  // each @font-face is preceded by a "/* subset */" comment
  const faces = [...css.matchAll(/\/\* ([\w-]+) \*\/\s*(@font-face \{[^}]+\})/g)];
  let n = 0;
  for (const [, subset, face] of faces) {
    if (!SUBSETS.includes(subset)) continue;
    const url = face.match(/url\((https:[^)]+)\)/)[1];
    const file = `${family.name}-${subset}.woff2`;
    const data = Buffer.from(await (await fetch(url, { headers: { "user-agent": UA } })).arrayBuffer());
    writeFileSync(`${OUT_DIR}/${file}`, data);
    const size = Math.round(data.length / 1024);
    blocks.push(`/* ${family.name} ${subset} (${size} KB) */\n${face.replace(url, `/fonts/${file}`)}`);
    n++;
  }
  console.log(`${family.name}: ${n} file(s)`);
}

// the licences travel with the files
for (const family of FAMILIES) {
  const url = `https://raw.githubusercontent.com/google/fonts/main/ofl/${family.ofl}/OFL.txt`;
  writeFileSync(`${OUT_DIR}/OFL-${family.name}.txt`, await text(url));
}

writeFileSync(
  CSS_OUT,
  `/* Generated by scripts/fetch-fonts.mjs. Do not edit by hand. */\n\n${blocks.join("\n\n")}\n`,
);
console.log(`wrote ${CSS_OUT}`);
