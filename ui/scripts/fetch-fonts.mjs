// Download the fonts into public/fonts and write src/styles/fonts.css, so the UI works
// offline and never shows icon names as text while a CDN is slow.
//
//   npm run fetch:fonts
//
// Google Sans Flex and Google Sans Code: Latin subsets. Material Symbols Rounded: only the
// icons listed in src/components/icons.ts. Run again after adding an icon there.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));
const OUT_DIR = root("public/fonts");
const CSS_OUT = root("src/styles/fonts.css");
// Google Fonts serves variable woff2 only to browsers it recognises
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36";

const icons = [...readFileSync(root("src/components/icons.ts"), "utf8").matchAll(/^ {2}"([a-z0-9_]+)",$/gm)]
  .map((m) => m[1])
  .sort();

const FAMILIES = [
  {
    name: "google-sans-flex",
    query: "family=Google+Sans+Flex:opsz,wdth,wght,ROND@6..144,25..151,1..1000,0..100",
    subsets: ["latin", "latin-ext"],
  },
  {
    name: "google-sans-code",
    query: "family=Google+Sans+Code:wght@300..600",
    subsets: ["latin", "latin-ext"],
  },
  {
    name: "material-symbols-rounded",
    query: `family=Material+Symbols+Rounded:opsz,wght,FILL,GRAD@20..48,100..700,0..1,-50..200&icon_names=${icons.join(",")}`,
    subsets: null, // one file, no unicode-range
  },
];

async function text(url) {
  const res = await fetch(url, { headers: { "user-agent": UA } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.text();
}

rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });
const blocks = [];
for (const family of FAMILIES) {
  const css = await text(`https://fonts.googleapis.com/css2?${family.query}&display=swap`);
  // each @font-face is preceded by a "/* subset */" comment (except for icon subsets)
  const faces = [...css.matchAll(/(?:\/\* ([\w-]+) \*\/\s*)?(@font-face \{[^}]+\})/g)];
  let n = 0;
  for (const [, subset, face] of faces) {
    if (family.subsets && !family.subsets.includes(subset)) continue;
    const url = face.match(/url\((https:[^)]+)\)/)[1];
    const file = `${family.name}${subset ? `-${subset}` : ""}.woff2`;
    const data = Buffer.from(await (await fetch(url, { headers: { "user-agent": UA } })).arrayBuffer());
    writeFileSync(`${OUT_DIR}/${file}`, data);
    blocks.push(
      `/* ${family.name}${subset ? ` ${subset}` : ""} (${Math.round(data.length / 1024)} KB) */\n${face.replace(url, `/fonts/${file}`).replace("font-display: swap", family.subsets ? "font-display: swap" : "font-display: block")}`,
    );
    n++;
  }
  console.log(`${family.name}: ${n} file(s)`);
}

// the licences travel with the files
for (const [file, url] of [
  [
    "OFL-google-sans-flex.txt",
    "https://raw.githubusercontent.com/google/fonts/main/ofl/googlesansflex/OFL.txt",
  ],
  [
    "OFL-google-sans-code.txt",
    "https://raw.githubusercontent.com/google/fonts/main/ofl/googlesanscode/OFL.txt",
  ],
  [
    "LICENSE-material-symbols.txt",
    "https://raw.githubusercontent.com/google/material-design-icons/master/LICENSE",
  ],
]) {
  writeFileSync(`${OUT_DIR}/${file}`, await text(url));
}

writeFileSync(
  CSS_OUT,
  `/* Generated by scripts/fetch-fonts.mjs. Do not edit by hand. */\n\n${blocks.join("\n\n")}\n`,
);
console.log(`wrote ${CSS_OUT} (${icons.length} icons)`);
